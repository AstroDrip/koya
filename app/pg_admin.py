"""Offline PostgreSQL initialization and verified import of a SQLite snapshot."""

import argparse
from contextlib import closing
import hashlib
import json
from pathlib import Path
import re
import sqlite3

from .database import SCHEMA, STAFF_SCHEMA, OTP_CHANNEL_COLUMN, SCHEMA_VERSION, now_iso
from .crm_schema import CRM_SCHEMA
from .dispatch_schema import DISPATCH_SCHEMA
from .finance_schema import FINANCE_SCHEMA, IMMUTABLE_FINANCE_TABLES
from .voice_schema import VOICE_SCHEMA
from .whatsapp_schema import WHATSAPP_SCHEMA
from .reliability_schema import RELIABILITY_SCHEMA, RECORDING_STORAGE_COLUMNS
from .postgres import database_url

SCHEMAS = (SCHEMA, STAFF_SCHEMA, CRM_SCHEMA, DISPATCH_SCHEMA, VOICE_SCHEMA, WHATSAPP_SCHEMA, FINANCE_SCHEMA, RELIABILITY_SCHEMA)
TABLE = re.compile(r"CREATE TABLE (?:IF NOT EXISTS )?(\w+)")
REFERENCES = re.compile(r"REFERENCES\s+(\w+)")
IMMUTABLE = ("crm_case_history", "dispatch_audit", *IMMUTABLE_FINANCE_TABLES)


def _ddl():
    tables, indexes = {}, []
    for schema in SCHEMAS:
        for statement in (statement.strip() for statement in schema.split(";")):
            match = TABLE.match(statement)
            if match:
                tables[match[1]] = statement
            elif statement.startswith("CREATE ") and " INDEX " in statement:
                indexes.append(statement)
    ordered = {}
    while tables:
        ready = [name for name, ddl in tables.items() if (set(REFERENCES.findall(ddl)) - {name}) <= ordered.keys()]
        if not ready:
            raise RuntimeError("Database schema contains an unresolved reference.")
        for name in ready:
            ordered[name] = tables.pop(name)
    return ordered, indexes


def _portable(ddl):
    ddl = re.sub(r"\bid INTEGER PRIMARY KEY(?: AUTOINCREMENT)?(?=\s*[,\)])",
                 "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ddl)
    ddl = re.sub(r"\bINTEGER\b", "BIGINT", ddl)
    ddl = re.sub(r"\bREAL\b", "DOUBLE PRECISION", ddl)
    return ddl.replace("ifnull(", "coalesce(")


def _production_connection():
    import psycopg

    dsn = database_url()
    if not dsn:
        raise ValueError("Configure MRCARE_DATABASE_URL before running PostgreSQL administration.")
    return psycopg.connect(dsn, connect_timeout=5)


def _initialize(conn):
    tables, indexes = _ddl()
    conn.execute("SELECT pg_advisory_xact_lock(1903147721)")
    conn.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version BIGINT PRIMARY KEY, applied_at TEXT NOT NULL)")
    versions = {row[0] for row in conn.execute("SELECT version FROM schema_migrations")}
    if versions == set(range(1, SCHEMA_VERSION + 1)):
        return
    if versions:
        raise RuntimeError("Unsupported PostgreSQL migration history.")
    for ddl in tables.values():
        conn.execute(_portable(ddl))
    conn.execute(OTP_CHANNEL_COLUMN)
    for statement in RECORDING_STORAGE_COLUMNS:
        conn.execute(_portable(statement))
    for index in indexes:
        conn.execute(_portable(index))
    conn.execute("""CREATE FUNCTION mrcare_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
                    BEGIN RAISE EXCEPTION 'Record is append-only' USING ERRCODE='23514'; END $$""")
    for table in IMMUTABLE:
        conn.execute(f"""CREATE TRIGGER {table}_immutable BEFORE UPDATE OR DELETE ON {table}
                         FOR EACH ROW EXECUTE FUNCTION mrcare_append_only()""")
    conn.execute("""CREATE FUNCTION mrcare_sealed_estimate() RETURNS trigger LANGUAGE plpgsql AS $$
                    BEGIN IF EXISTS(SELECT 1 FROM fin_estimate_events WHERE estimate_id=NEW.estimate_id)
                    THEN RAISE EXCEPTION 'Submitted estimate lines are sealed' USING ERRCODE='23514'; END IF;
                    RETURN NEW; END $$""")
    conn.execute("""CREATE TRIGGER fin_estimate_lines_sealed BEFORE INSERT ON fin_estimate_lines
                    FOR EACH ROW EXECUTE FUNCTION mrcare_sealed_estimate()""")
    with conn.cursor() as cursor:
        cursor.executemany("INSERT INTO schema_migrations(version,applied_at) VALUES (%s,%s)",
                           [(version, now_iso()) for version in range(1, SCHEMA_VERSION + 1)])


def migrate():
    with _production_connection() as conn:
        _initialize(conn)


def _row_digest(rows):
    count = 0
    total = 0
    for row in rows:
        content = json.dumps(list(row), separators=(",", ":"), ensure_ascii=False, allow_nan=False)
        total = (total + int.from_bytes(hashlib.sha256(content.encode()).digest(), "big")) % (2**256)
        count += 1
    return count, total


def _copy_table(source, target, name, ddl):
    from psycopg import sql

    ident = sql.Identifier(name)
    source_rows = source.execute(f"SELECT * FROM {name}")
    columns = [entry[0] for entry in source_rows.description]
    column_sql = sql.SQL(",").join(map(sql.Identifier, columns))
    with target.cursor() as cursor:
        with cursor.copy(sql.SQL("COPY {} ({}) FROM STDIN").format(ident, column_sql)) as copy:
            source_check = _row_digest(_copy_rows(copy, source_rows))
    with target.cursor(name="mrcare_verify_" + name) as cursor:
        cursor.execute(sql.SQL("SELECT {} FROM {}").format(column_sql, ident))
        if _row_digest(cursor) != source_check:
            raise RuntimeError(f"Imported values differ for {name}.")
    if "GENERATED BY DEFAULT AS IDENTITY" in _portable(ddl):
        maximum = source.execute(f"SELECT max(id) FROM {name}").fetchone()[0] or 0
        if "AUTOINCREMENT" in ddl:
            sequence = source.execute("SELECT seq FROM sqlite_sequence WHERE name=?", (name,)).fetchone()
            if sequence:
                maximum = max(maximum, sequence[0])
        target.execute(sql.SQL("ALTER TABLE {} ALTER COLUMN id RESTART WITH {}").format(ident, sql.Literal(maximum + 1)))
    return source_check[0]


def _copy_rows(copy, rows):
    for row in rows:
        copy.write_row(row)
        yield row


def import_sqlite(snapshot):
    """Copy a current verified SQLite backup into an empty PostgreSQL database."""
    from psycopg import sql

    source_path = Path(snapshot).resolve(strict=True)
    tables, _ = _ddl()
    with closing(sqlite3.connect(source_path.as_uri() + "?mode=ro", uri=True)) as source:
        source.execute("BEGIN")
        if source.execute("PRAGMA integrity_check").fetchall() != [("ok",)] or source.execute("PRAGMA foreign_key_check").fetchone():
            raise ValueError("SQLite backup failed integrity or foreign-key validation.")
        versions = {row[0] for row in source.execute("SELECT version FROM schema_migrations")}
        if versions != set(range(1, SCHEMA_VERSION + 1)):
            raise ValueError("Migrate a verified SQLite copy to the current schema before importing.")
        with _production_connection() as target:
            _initialize(target)
            target.execute(sql.SQL("LOCK TABLE {} IN ACCESS EXCLUSIVE MODE").format(
                sql.SQL(",").join(map(sql.Identifier, tables)),
            ))
            for table in tables:
                if target.execute(sql.SQL("SELECT 1 FROM {} LIMIT 1").format(sql.Identifier(table))).fetchone():
                    raise ValueError("Import requires an empty PostgreSQL target.")
            return {table: _copy_table(source, target, table, ddl) for table, ddl in tables.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("migrate")
    importer = commands.add_parser("import-sqlite")
    importer.add_argument("--verified-backup", required=True, type=Path)
    args = parser.parse_args()
    if args.command == "migrate":
        migrate()
        print(f"PostgreSQL schema {SCHEMA_VERSION} is ready.")
    else:
        counts = import_sqlite(args.verified_backup)
        print(json.dumps({"tables": counts, "rows_verified": sum(counts.values())}, indent=2))


if __name__ == "__main__":
    main()
